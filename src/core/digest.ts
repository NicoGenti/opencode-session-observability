function modelLabel(model: ModelRef | null | undefined): string {
  if (!model) return "—";
  return `${model.providerID}/${model.id}${model.variant ? `#${model.variant}` : ""}`;
}

function speedText(metric: Metric): string {
  return metric.value === null ? "—" : `${metric.value.toFixed(1)} tok/s`;
}

function toolNamesOf(step: Step): string[] {
  const names: string[] = [];
  const source =
    step.toolCalls.length > 0
      ? step.toolCalls.map((tool: ToolCallDetail) => tool.name)
      : step.toolNames;
  for (const name of source) {
    if (!names.includes(name)) names.push(name);
  }
  return names;
}

function turnToolNames(turn: Turn): string[] {
  const names: string[] = [];
  for (const step of orderedSteps(turn.steps)) {
    for (const name of toolNamesOf(step)) {
      if (!names.includes(name)) names.push(name);
    }
  }
  return names;
}

function clip(value: string, max: number): string {
  return value.length <= max ? value : `${value.slice(0, max)}…`;
}

function orderedTurns(turns: Turn[]): Turn[] {
  return [...turns].sort((a, b) => a.index - b.index);
}

function orderedSteps(steps: Step[]): Step[] {
  return [...steps].sort((a, b) => a.index - b.index);
}

function orderedCompactions(
  compactions: CompactionTransaction[],
): CompactionTransaction[] {
  return [...compactions].sort((a, b) => a.timestamp - b.timestamp);
}

function table(headers: string[], rows: string[][]): string[] {
  const head = `| ${headers.map(escapeMarkdownCell).join(" | ")} |`;
  const separator = `| ${headers.map(() => "---").join(" | ")} |`;
  return [
    head,
    separator,
    ...rows.map(
      (row) => `| ${row.map((cell) => escapeMarkdownCell(cell)).join(" | ")} |`,
    ),
  ];
}
