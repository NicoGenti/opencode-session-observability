// Selection and limits
// ---------------------------------------------------------------------------

/**
 * Keeps the most recent turns plus every errored or interrupted turn, unioned
 * and sorted ascending. Error turns are never dropped by recency.
 */
function selectTurns(turns: Turn[]): Turn[] {
  const ordered = orderedTurns(turns);
  const picked = [
    ...ordered.slice(-DIGEST_RECENT_TURNS),
    ...ordered.filter(
      (turn) => turn.status === "error" || turn.status === "interrupted",
    ),
  ];
  const seen = new Set<string>();
  const selected: Turn[] = [];
  for (const turn of picked) {
    if (seen.has(turn.id)) continue;
    seen.add(turn.id);
    selected.push(turn);
  }
  return selected.sort((a, b) => a.index - b.index);
}

function pushCapped(
  lines: string[],
  entries: string[],
  limit: number,
  label: string,
  options: { keepLast?: boolean } = {},
): void {
  if (entries.length === 0) {
    lines.push("None recorded.");
    return;
  }
  const shown = options.keepLast
    ? entries.slice(Math.max(0, entries.length - limit))
    : entries.slice(0, limit);
  lines.push(...shown);
  if (entries.length > shown.length) {
    lines.push(
      `[truncated: ${entries.length - shown.length} of ${entries.length} ${label} omitted]`,
    );
  }
}

/** Final deterministic cut on a line boundary, keeping the footer intact. */
function applyHardLimit(value: string): string {
  if (value.length <= DIGEST_MAX_CHARS) return value;
  const footer = `\n${FOOTER}`;
  const body = value.endsWith(footer)
    ? value.slice(0, value.length - footer.length)
    : value;
  const lines = body.split("\n");
  const build = (count: number): string => {
    const kept = lines.slice(0, count).join("\n");
    const omitted = body.length - kept.length;
    return `${kept}\n[digest truncated: ${omitted} chars omitted]${footer}`;
  };
  let low = 0;
  let high = lines.length;
  while (low < high) {
    const mid = Math.ceil((low + high) / 2);
    if (build(mid).length <= DIGEST_MAX_CHARS) low = mid;
    else high = mid - 1;
  }
  const result = build(low);
  return result.length <= DIGEST_MAX_CHARS
    ? result
    : result.slice(0, DIGEST_MAX_CHARS);
}

