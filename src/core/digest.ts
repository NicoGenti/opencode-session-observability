function totalsLines(totals: Totals): string[] {
  const lines = [
    `- Turns: ${formatNumber(totals.turns)}`,
    `- Steps: ${formatNumber(totals.steps)}`,
    `- Tool calls: ${formatNumber(totals.toolCalls)}`,
    `- Subagent calls: ${formatNumber(totals.subagentCalls)}`,
    `- Errors: ${formatNumber(totals.errors.total)} (tool ${formatNumber(
      totals.errors.tool,
    )}, step ${formatNumber(totals.errors.step)}, session ${formatNumber(
      totals.errors.session,
    )})`,
    `- Retries: ${formatNumber(totals.retries)}`,
    `- Compactions: ${formatNumber(totals.compactions)}`,
    `- Input tokens: ${formatNumber(totals.tokens.input)}`,
    `- Output tokens: ${formatNumber(totals.tokens.output)}`,
    `- Reasoning tokens: ${formatNumber(totals.tokens.reasoning)}`,
    `- Cache read: ${formatNumber(totals.tokens.cacheRead)}`,
    `- Cache write: ${formatNumber(totals.tokens.cacheWrite)}`,
    `- Cache hit rate: ${formatPercent(totals.cacheHitRate.value)}`,
    `- Cost: ${formatCost(totals.cost.value)}`,
    `- Model time: ${formatDuration(totals.modelTime.value)}`,
    `- Tool time: ${formatDuration(totals.toolTime.value)}`,
    `- Active turn time: ${formatDuration(totals.activeTurnTime.value)}`,
    `- Wall clock: ${formatDuration(totals.wallClockTime.value)}`,
    `- Output speed: ${speedText(totals.outputSpeed)}`,
    `- Final context: ${formatNumber(totals.finalContext.value)}`,
    `- Cumulative prompt: ${formatNumber(totals.cumulativePrompt.value)}`,
  ];
  if (totals.recorded) {
    const recorded = totals.recorded;
    const parts: string[] = [];
    if (recorded.tokens) {
      parts.push(
        `tokens input ${formatNumber(recorded.tokens.input)}, output ${formatNumber(
          recorded.tokens.output,
        )}, reasoning ${formatNumber(
          recorded.tokens.reasoning,
        )}, cache read ${formatNumber(
          recorded.tokens.cacheRead,
        )}, cache write ${formatNumber(recorded.tokens.cacheWrite)}`,
      );
    }
    if (recorded.cost !== undefined) {
      parts.push(`cost ${formatCost(recorded.cost)}`);
    }
    parts.push(recorded.note);
    lines.push(`- Recorded by OpenCode: ${parts.join(" · ")}`);
  }
  return lines;
}

function toolAggregates(turns: Turn[]): string[][] {
  const aggregates = new Map<
    string,
    { calls: number; errors: number; duration: number; durationKnown: boolean }
  >();
  for (const turn of orderedTurns(turns)) {
    for (const step of orderedSteps(turn.steps)) {
      for (const tool of step.toolCalls) {
        const entry = aggregates.get(tool.name) ?? {
          calls: 0,
          errors: 0,
          duration: 0,
          durationKnown: false,
        };
        entry.calls += 1;
        if (tool.error || tool.status === "error") entry.errors += 1;
        if (tool.duration.value !== null) {
          entry.duration += tool.duration.value;
          entry.durationKnown = true;
        }
        aggregates.set(tool.name, entry);
      }
    }
  }
  return [...aggregates.entries()]
    .sort((a, b) => {
      if (a[1].calls !== b[1].calls) return b[1].calls - a[1].calls;
      return a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0;
    })
    .map(([name, entry]) => [
      name,
      String(entry.calls),
      String(entry.errors),
      entry.durationKnown ? formatDuration(entry.duration) : "—",
    ]);
}

function rankExpensiveSteps(turns: Turn[]): string[][] {
  const candidates: Array<{ turn: number; step: Step; cost: number; time: number }> = [];
  for (const turn of orderedTurns(turns)) {
    for (const step of orderedSteps(turn.steps)) {
      const cost = step.cost;
      const time = step.totalTime.value;
      if ((cost ?? 0) <= 0 && (time ?? 0) <= 0) continue;
      candidates.push({ turn: turn.index, step, cost: cost ?? -1, time: time ?? -1 });
    }
  }
  candidates.sort((a, b) => {
    if (a.cost !== b.cost) return b.cost - a.cost;
    if (a.time !== b.time) return b.time - a.time;
    if (a.turn !== b.turn) return a.turn - b.turn;
    return a.step.index - b.step.index;
  });
  return candidates.map(({ turn, step }) => [
    `${turn}.${step.index}`,
    toolNamesOf(step).join(", ") || "—",
    formatCost(step.cost),
    formatDuration(step.totalTime.value),
  ]);
}

function compactionLines(compactions: CompactionTransaction[]): string[] {
  return orderedCompactions(compactions).map(
    (item) =>
      `- ${formatDateTime(item.timestamp)} — context ${formatNumber(
        item.contextBefore.value,
      )} → ${formatNumber(item.contextAfter.value)}, removed ${formatNumber(
        item.removedTokens.value,
      )} tokens, summary ${formatNumber(
        item.summaryChars,
      )} chars, cost ${formatCost(item.cost)}`,
  );
}

function collectErrors(
  turns: Turn[],
  events: EventIndexEntry[],
): string[] {
  const entries: string[] = [];
  for (const turn of orderedTurns(turns)) {
    for (const step of orderedSteps(turn.steps)) {
      if (step.status === "error") {
        const detail = step.finish
          ? `: ${clip(escapeMarkdownInline(step.finish), DIGEST_MAX_ERROR_MESSAGE)}`
          : "";
        entries.push(`- Turn ${turn.index}.${step.index} — step error${detail}`);
      }
      for (const tool of step.toolCalls) {
        if (tool.error) {
          entries.push(
            `- Turn ${turn.index}.${step.index} tool ${escapeMarkdownInline(
              tool.name,
            )} — ${escapeMarkdownInline(tool.error.type)}: ${clip(
              escapeMarkdownInline(tool.error.message),
              DIGEST_MAX_ERROR_MESSAGE,
            )}`,
          );
        } else if (tool.status === "error") {
          entries.push(
            `- Turn ${turn.index}.${step.index} tool ${escapeMarkdownInline(
              tool.name,
            )} — tool error (no detail recorded)`,
          );
        }
      }
    }
  }
  // Session-level errors have no turn of their own: the session row reported a
  // failed or interrupted idle outcome, which `totals.errors.session` counts.
  // Recorded event order keeps the list deterministic.
  for (const event of events) {
    if (event.kind !== "idle") continue;
    if (event.status !== "failed" && event.status !== "interrupted") continue;
    entries.push(
      `- Session — ${event.status} at ${formatDateTime(event.timestamp)}`,
    );
  }
  return entries;
}

function turnRow(turn: Turn): string[] {
  const tools = turnToolNames(turn);
  return [
    String(turn.index),
    turn.trigger.label,
    String(turn.steps.length),
    tools.length > 0 ? clip(tools.join(", "), DIGEST_MAX_TOOL_NAMES) : "—",
    formatNumber(turn.tokens.input),
    formatNumber(turn.tokens.output),
    formatCost(turn.cost.value),
    formatDuration(turn.totalTime.value),
    turn.status,
  ];
}

