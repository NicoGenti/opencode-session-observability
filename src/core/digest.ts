/**
 * Deterministic, size-capped Markdown digest of a normalized session analysis.
 *
 * The digest is a pure function of the caller-redacted projection: it never
 * reads `analysis.generatedAt`, never consults the current time and never
 * performs I/O, so the same input always renders byte-identical output. It is
 * intended as review material for an LLM of the user's choice; the application
 * itself performs no network calls.
 */
import {
  escapeMarkdownCell,
  escapeMarkdownInline,
  formatCost,
  formatDateTime,
  formatDuration,
  formatNumber,
  formatPercent,
} from "./format.ts";
import type {
  Analysis,
  CompactionTransaction,
  EventIndexEntry,
  Metric,
  ModelRef,
  SessionMeta,
  Step,
  ToolCallDetail,
  Totals,
  Turn,
} from "./types.ts";

/** Hard upper bound on the rendered digest length, in characters. */
export const DIGEST_MAX_CHARS = 16_000;

const DIGEST_RECENT_TURNS = 25;
const DIGEST_MAX_ERRORS = 20;
const DIGEST_MAX_RETRY_TURNS = 20;
const DIGEST_MAX_COMPACTIONS = 10;
const DIGEST_MAX_TOOL_ROWS = 15;
const DIGEST_MAX_EXPENSIVE_STEPS = 10;
const DIGEST_MAX_ERROR_MESSAGE = 300;
const DIGEST_MAX_TOOL_NAMES = 60;

const FOOTER =
  "Generated by opencode-session-observability — deterministic digest.";
const REDACTED_BANNER =
  "> Redacted: credential-shaped values were replaced with [REDACTED].";
const UNREDACTED_BANNER =
  "> UNREDACTED: generated with reveal active — contains unredacted secrets. Share only with tools you trust.";

/**
 * Review instructions prepended to a digest. One canonical source for the
 * endpoint and the plugin RPC, so no client duplicates the template. The list
 * is joined with `\n` to keep the verbatim line structure exact.
 */
export const REVIEW_PROMPT_INSTRUCTIONS = [
  "You are reviewing an OpenCode coding-agent session from its observability data.",
  "Assess whether the session was effective, efficient, and safe. Do not invent facts",
  "that are not supported by the supplied data.",
  "Analyze:",
  "1. Outcome: Did the agent appear to complete the requested work? Identify unfinished",
  "   or uncertain work.",
  "2. Efficiency: Identify wasted turns, repeated tool calls, unnecessary exploration,",
  "   retry loops, and expensive steps.",
  "3. Context management: Identify context growth, compaction events, cache reuse, and",
  "   possible loss of relevant context.",
  "4. Tool usage: Identify failed tools, repeated failures, slow tools, and suspicious",
  "   parameter choices.",
  "5. Errors: Identify root causes, recurrence patterns, and the earliest point where",
  "   intervention would have helped.",
  "6. Recommendations: Provide at most five concrete, actionable improvements for the",
  "   next session. Separate facts from hypotheses.",
  "Return this structure:",
  "- Verdict: effective / partially effective / ineffective",
  "- Key findings",
  "- Inefficiencies",
  "- Failure analysis",
  "- Context and cost observations",
  "- Recommended next-session changes",
  "- Open questions",
  "Be concise and evidence-based. Refer to turn numbers and tool names where possible.",
  "SESSION DIGEST:",
].join("\n");

/**
 * Assembles the full review prompt: optional unredacted warning, the verbatim
 * instructions and the digest, whose title immediately follows the template's
 * closing `SESSION DIGEST:` line.
 */
export function buildReviewPrompt(
  digest: string,
  options: { unredacted: boolean },
): string {
  const warning = options.unredacted ? `${UNREDACTED_BANNER}\n\n` : "";
  return `${warning}${REVIEW_PROMPT_INSTRUCTIONS}\n${digest}`;
}

export interface SessionDigestInput {
  session: SessionMeta;
  analysis: Analysis;
  unredacted: boolean;
}

/**
 * Renders the digest for one session. See the module comment for the purity
 * guarantees; every ordering, limit and marker below is fixed so that two
 * calls with equal input produce equal output.
 */
export function buildSessionDigest(input: SessionDigestInput): string {
  const { session, analysis, unredacted } = input;
  const totals = analysis.totals;
  const lines: string[] = [];

  // 1. Title and metadata.
  const title = session.title ?? session.slug ?? session.id;
  lines.push(`# Session digest — ${escapeMarkdownInline(title)}`, "");
  lines.push(
    `- Session: \`${escapeMarkdownInline(session.id)}\``,
    `- Agent: \`${escapeMarkdownInline(session.agent ?? "—")}\``,
    `- Model: \`${escapeMarkdownInline(modelLabel(session.model))}\``,
    `- Created: ${formatDateTime(session.time.created)}`,
    `- Updated: ${formatDateTime(session.time.updated ?? null)}`,
    `- Outcome: ${session.outcome ?? "—"}`,
    `- Source: ${analysis.capabilities.source} (${
      analysis.coverage.complete ? "full session" : "window"
    })`,
    "",
  );

  // 2. Redaction status.
  lines.push(unredacted ? UNREDACTED_BANNER : REDACTED_BANNER, "");

  // 3. Totals.
  lines.push("## Totals", "");
  lines.push(...totalsLines(totals));
  lines.push("");

  // 4. Errors.
  lines.push("## Errors", "");
  pushCapped(
    lines,
    collectErrors(analysis.turns, analysis.events),
    DIGEST_MAX_ERRORS,
    "errors",
  );
  lines.push("");

  // 5. Retries.
  lines.push("## Retries", "");
  lines.push(`Retries recorded in totals: ${formatNumber(totals.retries)}.`);
  const retryTurns = analysis.turns.filter(
    (turn) => turn.trigger.kind === "retry",
  );
  if (retryTurns.length === 0) {
    if (totals.retries === 0) lines.push("None recorded.");
  } else {
    pushCapped(
      lines,
      retryTurns.map(
        (turn) => `- Turn ${turn.index} — ${escapeMarkdownInline(turn.trigger.label)}`,
      ),
      DIGEST_MAX_RETRY_TURNS,
      "retry turns",
    );
  }
  lines.push("");

  // 6. Compactions (the cap keeps the most recent; rows render chronologically).
  lines.push("## Compactions", "");
  pushCapped(
    lines,
    compactionLines(analysis.compactions),
    DIGEST_MAX_COMPACTIONS,
    "compactions",
    { keepLast: true },
  );
  lines.push("");

  // 7. Notable tool activity.
  lines.push("## Notable tool activity", "");
  const toolRows = toolAggregates(analysis.turns);
  const stepRows = rankExpensiveSteps(analysis.turns);
  if (toolRows.length === 0 && stepRows.length === 0) {
    lines.push("None recorded.");
  } else {
    const blocks: string[][] = [];
    if (toolRows.length > 0) {
      const shown = toolRows.slice(0, DIGEST_MAX_TOOL_ROWS);
      const block = [
        "### Tools",
        "",
        ...table(
          ["Tool", "Calls", "Errors", "Duration"],
          shown,
        ),
      ];
      if (toolRows.length > shown.length) {
        block.push(
          `[truncated: ${toolRows.length - shown.length} of ${toolRows.length} tools omitted]`,
        );
      }
      blocks.push(block);
    }
    if (stepRows.length > 0) {
      const shown = stepRows.slice(0, DIGEST_MAX_EXPENSIVE_STEPS);
      const block = [
        "### Expensive steps",
        "",
        ...table(
          ["Step", "Tools", "Cost", "Time"],
          shown,
        ),
      ];
      if (stepRows.length > shown.length) {
        block.push(
          `[truncated: ${stepRows.length - shown.length} of ${stepRows.length} expensive steps omitted]`,
        );
      }
      blocks.push(block);
    }
    blocks.forEach((block, index) => {
      if (index > 0) lines.push("");
      lines.push(...block);
    });
  }
  lines.push("");

  // 8. Turn summary.
  lines.push("## Turn summary", "");
  const selected = selectTurns(analysis.turns);
  if (selected.length === 0) {
    lines.push("None recorded.");
  } else {
    lines.push(
      ...table(
        ["#", "Trigger", "Steps", "Tools", "In", "Out", "Cost", "Duration", "Status"],
        selected.map(turnRow),
      ),
    );
    const dropped = analysis.turns.length - selected.length;
    if (dropped > 0) {
      lines.push(
        `[truncated: ${dropped} of ${analysis.turns.length} turns omitted]`,
      );
    }
  }
  lines.push("");

  // 9. Footer, then the hard size bound.
  lines.push(FOOTER);
  return applyHardLimit(lines.join("\n"));
}

